export function translate(lang, key, vars) {
  const path = key.split('.');
  const lookup = (dict) => path.reduce((node, segment) => (node == null ? undefined : node[segment]), dict);

  let value = lookup(translations[lang]);
  if (value === undefined) {
    value = lookup(translations[DEFAULT_LANGUAGE]);
  }
  if (value === undefined) {
    return key;
  }
  if (typeof value === 'string' && vars) {
    return value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] !== undefined ? String(vars[name]) : match));
  }
  return value;
}

